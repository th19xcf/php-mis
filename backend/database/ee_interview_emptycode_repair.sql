-- ============================================================================
-- ee_interview 空码补链修复（2026-08-26 执行）
-- ============================================================================
-- 背景：
--   ee_interview 存在 44 行活跃记录（GUID 21267~21310），候选人编码为空，
--   操作人员=丰小叶、操作时间=2026-08-25 16:30:48、无操作来源（直导入）。
--   无候选人编码 → 无法流转培训（业务 blocked）。
--
-- 勘察结论（2026-08-26）：
--   * 44/44 一次面试结果=通过、一次面试日期=2026-08-17、预约培训日期=2026-08-18
--   * 44/44 人员编码齐（hr_person 已建主档 PK20260817001~044）
--   * 44/44 身份证号/手机号码/属地/招聘渠道/渠道类型/渠道名称/面试业务/面试岗位 齐
--   * ee_store 无同证人（含失效行）→ 判定为绕过邀约流程的直接导入，无源头可挂码
--
-- 处置（补链修复，非失效——44 人面试通过待流转培训，失效将丢失业务数据）：
--   0. ee_store 补普通索引（reconcile ⑤ 口径修正的 EXISTS 性能依赖）
--   1. 发 44 个新码（业务日期=面试日期 2026-08-17，def_seq 分桶发号）
--   2. 补建 ee_store 源头行（携带渠道/岗位等实例级字段，身份字段源自面试表）
--   3. 补建 ee_application 实例（当前阶段=面试，时间线=邀约日期+面试日期）
--   4. 回填 ee_interview.候选人编码
--
-- 注意：单次执行脚本。重跑前须先跑第 0 部分核验——目标行数为 0 时跳过
--       第 1~4 部分（否则会重复发号、重复建源；同码活跃行由
--       uk_候选人编码_活跃 函数唯一索引拦截报错）。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 第 0 部分：预检与索引
-- ---------------------------------------------------------------------------

-- 0.1 目标行确认（应返回 44；返回 0 说明已修复，勿继续执行）
SELECT COUNT(*) AS 待修复行数
FROM ee_interview
WHERE IFNULL(候选人编码, '') = '' AND 有效标识 = '1' AND 删除标识 = '0';

-- 0.2 ee_store 补普通索引（函数唯一索引只覆盖活跃行码，归档判断需全状态码索引）
ALTER TABLE ee_store ADD INDEX idx_候选人编码 (候选人编码);

-- ---------------------------------------------------------------------------
-- 第 1 部分：发号（44 个，业务日期=面试日期）
-- ---------------------------------------------------------------------------

CALL sp_生成候选人编码(44, '2026-08-17', @seq, @prefix);
-- @prefix = 'C20260817'，@seq = 段首号；码区间 [prefix+LPAD(seq,3,0), prefix+LPAD(seq+43,3,0)]

-- ---------------------------------------------------------------------------
-- 第 2 部分：补链修复（事务）
-- ---------------------------------------------------------------------------

START TRANSACTION;

-- 2.1 补建 ee_store 源头行（性别/年龄自身份证号派生；邀约业务/岗位承接面试业务/岗位）
INSERT INTO ee_store (候选人编码, 人员编码, 姓名, 身份证号, 手机号码, 属地,
    性别, 年龄, 招聘渠道, 渠道类型, 渠道名称, 邀约业务, 邀约岗位,
    邀约日期, 预约面试日期, 面试信息,
    操作记录, 操作来源, 操作人员, 开始操作时间, 操作时间, 删除标识, 有效标识)
SELECT CONCAT(@prefix, LPAD(@seq + i.rn - 1, 3, '0')),
       i.人员编码, i.姓名, i.身份证号, i.手机号码, i.属地,
       IF(MOD(SUBSTR(i.身份证号, 17, 1), 2) = 1, '男', '女'),
       TIMESTAMPDIFF(YEAR, STR_TO_DATE(SUBSTR(i.身份证号, 7, 8), '%Y%m%d'), CURDATE()),
       i.招聘渠道, i.渠道类型, i.渠道名称, i.面试业务, i.面试岗位,
       '2026-08-17', i.一次面试日期, '已面试',
       '补链修复：直导面试数据补建邀约源', '数据修复', i.操作人员,
       NOW(), i.操作时间, '0', '1'
FROM (
    SELECT t.*, ROW_NUMBER() OVER (ORDER BY t.GUID) AS rn
    FROM ee_interview t
    WHERE IFNULL(t.候选人编码, '') = '' AND t.有效标识 = '1' AND t.删除标识 = '0'
) i;

-- 2.2 补建 ee_application 实例（当前阶段=面试）
INSERT INTO ee_application (候选人编码, 人员编码, 当前阶段, 邀约日期, 面试日期,
    操作记录, 操作来源, 操作人员, 开始操作时间)
SELECT s.候选人编码, s.人员编码, '面试', '2026-08-17', '2026-08-17',
       '补链修复', '数据修复', s.操作人员, NOW()
FROM ee_store s
WHERE s.操作来源 = '数据修复' AND s.有效标识 = '1' AND s.删除标识 = '0'
  AND NOT EXISTS (SELECT 1 FROM ee_application a WHERE a.候选人编码 = s.候选人编码);

-- 2.3 回填面试表候选人编码
UPDATE ee_interview i
JOIN ee_store s ON s.身份证号 = i.身份证号 AND s.操作来源 = '数据修复'
SET i.候选人编码 = s.候选人编码
WHERE IFNULL(i.候选人编码, '') = '' AND i.有效标识 = '1' AND i.删除标识 = '0';

COMMIT;

-- ---------------------------------------------------------------------------
-- 第 3 部分：核验（三项均应返回 44 / 0 / 0）
-- ---------------------------------------------------------------------------

-- 3.1 面试表空码剩余（应 0）
SELECT COUNT(*) AS 空码剩余
FROM ee_interview
WHERE IFNULL(候选人编码, '') = '' AND 有效标识 = '1' AND 删除标识 = '0';

-- 3.2 修复行实例与源头齐备（应 44：新源头行均有实例且面试行已挂码）
SELECT COUNT(*) AS 链完整
FROM ee_store s
JOIN ee_application a ON a.候选人编码 = s.候选人编码
JOIN ee_interview i ON i.候选人编码 = s.候选人编码
WHERE s.操作来源 = '数据修复' AND s.有效标识 = '1' AND s.删除标识 = '0';

-- 3.3 修复行孤儿检查（应 0）
SELECT COUNT(*) AS 修复行孤儿
FROM ee_store s
LEFT JOIN ee_application a ON a.候选人编码 = s.候选人编码
WHERE s.操作来源 = '数据修复' AND s.有效标识 = '1' AND s.删除标识 = '0'
  AND a.候选人编码 IS NULL;
