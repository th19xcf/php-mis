-- -----------------------------------------------------------------------------
-- 0. 清理旧示例数据（按需执行，仅清理示例路由，不影响真实配置）
-- -----------------------------------------------------------------------------
DELETE FROM `def_workflow_routing`
WHERE `业务类型` = 'CONTRACT'
  AND `路由编码` IN (
    'CONTRACT_PURCHASE_HIGH',
    'CONTRACT_PURCHASE_NORMAL',
    'CONTRACT_SALES',
    'CONTRACT_DEFAULT'
  );

-- -----------------------------------------------------------------------------
-- 1. 示例一：采购合同 + 高金额（≥100万）→ 走"采购合同高额审批"流程
--    目标流程编码：contract_purchase_high_approval
-- -----------------------------------------------------------------------------
INSERT INTO `def_workflow_routing`
  (`业务类型`, `路由编码`, `路由名称`, `匹配条件`, `目标流程编码`, `优先级`,
   `启用状态`, `路由描述`,
   `创建人`, `创建时间`, `更新人`, `更新时间`)
VALUES
  ('CONTRACT', 'CONTRACT_PURCHASE_HIGH', '采购合同-高额',
   JSON_OBJECT(
     '合同类型', '采购合同',
     '合同金额', JSON_OBJECT('>=', 1000000)
   ),
   'contract_purchase_high_approval',
   10,
   '1',
   '采购合同且金额≥100万，走三级审批（部门→财务→总经理）',
   'system', NOW(), 'system', NOW());

-- -----------------------------------------------------------------------------
-- 2. 示例二：采购合同 + 普通金额（<100万）→ 走"采购合同普通审批"流程
--    目标流程编码：contract_approval（沿用原默认流程）
-- -----------------------------------------------------------------------------
INSERT INTO `def_workflow_routing`
  (`业务类型`, `路由编码`, `路由名称`, `匹配条件`, `目标流程编码`, `优先级`,
   `启用状态`, `路由描述`,
   `创建人`, `创建时间`, `更新人`, `更新时间`)
VALUES
  ('CONTRACT', 'CONTRACT_PURCHASE_NORMAL', '采购合同-普通',
   JSON_OBJECT(
     '合同类型', '采购合同',
     '合同金额', JSON_OBJECT('<', 1000000)
   ),
   'contract_approval',
   20,
   '1',
   '采购合同且金额<100万，走二级审批（部门→财务）',
   'system', NOW(), 'system', NOW());

-- -----------------------------------------------------------------------------
-- 3. 示例三：销售合同 → 走"销售合同审批"流程（不限制金额）
--    目标流程编码：contract_sales_approval
-- -----------------------------------------------------------------------------
INSERT INTO `def_workflow_routing`
  (`业务类型`, `路由编码`, `路由名称`, `匹配条件`, `目标流程编码`, `优先级`,
   `启用状态`, `路由描述`,
   `创建人`, `创建时间`, `更新人`, `更新时间`)
VALUES
  ('CONTRACT', 'CONTRACT_SALES', '销售合同',
   JSON_OBJECT('合同类型', '销售合同'),
   'contract_sales_approval',
   30,
   '1',
   '销售合同统一走销售审批流程',
   'system', NOW(), 'system', NOW());

-- -----------------------------------------------------------------------------
-- 4. 示例四：兜底路由（无任何匹配条件，优先级最低）
--    用于在所有路由都未命中时，提供一个默认流程
--    注意：匹配条件为 NULL 视为通配，建议仅在需要时启用
-- -----------------------------------------------------------------------------
INSERT INTO `def_workflow_routing`
  (`业务类型`, `路由编码`, `路由名称`, `匹配条件`, `目标流程编码`, `优先级`,
   `启用状态`, `路由描述`,
   `创建人`, `创建时间`, `更新人`, `更新时间`)
VALUES
  ('CONTRACT', 'CONTRACT_DEFAULT', '合同默认流程',
   NULL,
   'contract_approval',
   999,
   '1',
   '兜底路由：所有未匹配的合同走默认审批流程',
   'system', NOW(), 'system', NOW());

-- =============================================================================
-- 验证查询
-- =============================================================================
SELECT `GUID`, `业务类型`, `路由编码`, `路由名称`,
       `匹配条件`, `目标流程编码`, `优先级`, `启用状态`
FROM `def_workflow_routing`
WHERE `业务类型` = 'CONTRACT'
  AND `删除标识` = '0'
ORDER BY `优先级` ASC;

