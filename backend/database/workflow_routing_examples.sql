-- =============================================================================
-- def_workflow_routing 示例配置 SQL
-- 用途：根据合同类型/金额等条件，自动路由到不同审批流程
-- =============================================================================
-- 口径说明（务必遵守，历史踩坑记录）：
--   1. 业务类型统一用中文 '合同'（def_workflow_definition.业务类型 存量即此口径），
--      不要写成 'CONTRACT'，否则路由解析（业务类型入参）永不命中
--   2. 匹配条件中的 合同类型 必须用类型编码（采购合同 / 销售合同 / 服务合同 等，
--      来源 def_contract_type.类型编码，即主表 def_contract_master_new.合同类型 的存储值）。
--      2026-10-02 起 类型编码 已统一中文化（= 类型名称），匹配条件与主表存储值
--      均使用中文；切勿再写英文编码（PURCHASE/SALES/SERVICE...），否则路由永不命中
--   3. 目标流程编码必须在 def_workflow_definition 中真实存在且 流程状态='启用'，
--      指向不存在的流程编码会在 startProcess 时抛"未找到启用的流程定义"
-- =============================================================================
-- 前置条件：
--   1. 已执行 migration 创建 def_workflow_routing 表
--   2. def_workflow_definition 表中已存在对应的目标流程编码（如 '合同审批流程'）
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. 清理旧示例数据（按需执行，仅清理示例路由，不影响真实配置）
-- -----------------------------------------------------------------------------
DELETE FROM `def_workflow_routing`
WHERE `业务类型` = '合同'
  AND `路由编码` IN (
    'CONTRACT_PURCHASE_HIGH',
    'CONTRACT_PURCHASE_NORMAL',
    'CONTRACT_SALES',
    'CONTRACT_DEFAULT'
  );

-- -----------------------------------------------------------------------------
-- 1. 示例一：采购合同 + 高金额（≥100万）
--    当前暂无"高额采购"专属流程，统一走现有启用流程 '合同审批流程'；
--    将来创建专属流程（如 contract_purchase_high_approval）后，
--    仅需把本行 `目标流程编码` 改为该新流程编码即可，金额分桶结构保留不动
-- -----------------------------------------------------------------------------
INSERT INTO `def_workflow_routing`
  (`业务类型`, `路由编码`, `路由名称`, `匹配条件`, `目标流程编码`, `优先级`,
   `启用状态`, `路由描述`,
   `创建人`, `创建时间`, `更新人`, `更新时间`)
VALUES
  ('合同', 'CONTRACT_PURCHASE_HIGH', '采购合同-高额',
   JSON_OBJECT(
     '合同类型', '采购合同',
     '合同金额', JSON_OBJECT('>=', 1000000)
   ),
   '合同审批流程',
   10,
   '1',
   '采购合同（类型编码 采购合同）且金额≥100万，暂走通用合同审批流程',
   'system', NOW(), 'system', NOW());

